$ErrorActionPreference = "Stop"
$ROOT = "D:\Pyloom POS System"
$PSQL_BIN = "C:\Program Files\Odoo 17.0.20240709\PostgreSQL\bin"

Write-Host ""
Write-Host "==========================================" -ForegroundColor Cyan
Write-Host "   Pyloom POS — Initial Setup            " -ForegroundColor Cyan
Write-Host "   Powered by Pyloom Technologies        " -ForegroundColor Cyan
Write-Host "==========================================" -ForegroundColor Cyan
Write-Host ""

# Step 1: Configure npm cache on D:
Write-Host "[1/5] Configuring npm cache on D: drive..." -ForegroundColor Yellow
$NPM_CACHE = "$ROOT\.npm-cache"
if (-not (Test-Path $NPM_CACHE)) { New-Item -ItemType Directory -Path $NPM_CACHE -Force | Out-Null }
npm config set cache $NPM_CACHE --global
Write-Host "  npm cache set to: $NPM_CACHE" -ForegroundColor Green

# Step 2: Create PostgreSQL database and user
Write-Host ""
Write-Host "[2/5] Setting up PostgreSQL database..." -ForegroundColor Yellow
$PG_SUPERUSER = Read-Host "  Enter PostgreSQL superuser name (try 'admin' or 'postgres')"
$PG_SUPERPASS = Read-Host "  Enter password for '$PG_SUPERUSER'" -AsSecureString
$BSTR = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($PG_SUPERPASS)
$PG_PASS = [Runtime.InteropServices.Marshal]::PtrToStringAuto($BSTR)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($BSTR)

$PYLOOM_DB_PASS = Read-Host "  Set password for new 'pyloom_user' database account"

$env:PGPASSWORD = $PG_PASS
$psql = "$PSQL_BIN\psql.exe"

# Create pyloom_user role
Write-Host "  Creating pyloom_user role..." -ForegroundColor Gray
& $psql -U $PG_SUPERUSER -h localhost -p 5432 -d postgres -c "DO `$`$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='pyloom_user') THEN CREATE ROLE pyloom_user WITH LOGIN PASSWORD '$PYLOOM_DB_PASS'; END IF; END `$`$;" 2>&1

# Create pyloom_pos database
Write-Host "  Creating pyloom_pos database..." -ForegroundColor Gray
& $psql -U $PG_SUPERUSER -h localhost -p 5432 -d postgres -c "SELECT 1 FROM pg_database WHERE datname='pyloom_pos';" | Out-Null
& $psql -U $PG_SUPERUSER -h localhost -p 5432 -d postgres -c "CREATE DATABASE pyloom_pos OWNER pyloom_user ENCODING 'UTF8' LC_COLLATE 'C' LC_CTYPE 'C' TEMPLATE template0;" 2>&1

# Grant privileges
& $psql -U $PG_SUPERUSER -h localhost -p 5432 -d pyloom_pos -c "GRANT ALL PRIVILEGES ON DATABASE pyloom_pos TO pyloom_user; GRANT ALL ON SCHEMA public TO pyloom_user;" 2>&1

Write-Host "  Database setup complete!" -ForegroundColor Green
$env:PGPASSWORD = $null

# Step 3: Write connection string
Write-Host ""
Write-Host "[3/5] Writing backend .env configuration..." -ForegroundColor Yellow
$DB_URL = "postgresql://pyloom_user:$PYLOOM_DB_PASS@localhost:5432/pyloom_pos"
$ENV_CONTENT = @"
# Pyloom POS Backend Configuration
# Generated by setup.ps1

DATABASE_URL="$DB_URL"
JWT_SECRET="$(New-Guid)$(New-Guid)"
JWT_EXPIRES_IN="8h"
PORT=3000
NODE_ENV=development
UPLOAD_DIR="D:/Pyloom POS System/uploads"
REPORTS_DIR="D:/Pyloom POS System/reports/generated"
BACKUPS_DIR="D:/Pyloom POS System/backups"
TIMEZONE="Asia/Kathmandu"
CURRENCY="NPR"
"@

$BACKEND_DIR = "$ROOT\backend"
if (Test-Path $BACKEND_DIR) {
    Set-Content -Path "$BACKEND_DIR\.env" -Value $ENV_CONTENT
    Write-Host "  .env written to: $BACKEND_DIR\.env" -ForegroundColor Green
} else {
    Write-Host "  Backend not yet created. .env will be created during Phase 2." -ForegroundColor Yellow
    # Save to scripts for now
    Set-Content -Path "$ROOT\scripts\.env.template" -Value $ENV_CONTENT
    Write-Host "  Template saved to: $ROOT\scripts\.env.template" -ForegroundColor Green
}

# Step 4: Verify disk space
Write-Host ""
Write-Host "[4/5] Verifying disk space..." -ForegroundColor Yellow
$d = [System.IO.DriveInfo]::new("D")
$c = [System.IO.DriveInfo]::new("C")
Write-Host "  D: Free: $([math]::Round($d.AvailableFreeSpace/1GB, 2)) GB" -ForegroundColor $(if ($d.AvailableFreeSpace/1GB -gt 5) { "Green" } else { "Red" })
Write-Host "  C: Free: $([math]::Round($c.AvailableFreeSpace/1GB, 2)) GB" -ForegroundColor $(if ($c.AvailableFreeSpace/1GB -gt 1) { "Green" } else { "Red" })

# Step 5: Done
Write-Host ""
Write-Host "[5/5] Setup complete!" -ForegroundColor Green
Write-Host ""
Write-Host "==========================================" -ForegroundColor Green
Write-Host "   Next Step: Run Phase 2 to install     " -ForegroundColor Green
Write-Host "   frontend and backend dependencies.    " -ForegroundColor Green
Write-Host "==========================================" -ForegroundColor Green
Write-Host ""
Write-Host "DATABASE_URL: $DB_URL" -ForegroundColor Cyan
Write-Host ""
